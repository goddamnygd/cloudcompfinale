# MODELS
# ============================================================
Difficulty = Literal["Easy", "Intermediate", "Hard", "Very Hard"]
Role = Literal["Survivor", "Killer"]


class CharacterCreate(BaseModel):
    """Body for POST. The id is generated by the database."""
    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)

    name: str = Field(min_length=1)
    character_code: str = Field(min_length=1)
    role: Role
    gender: str = Field(min_length=1)
    origin: str = Field(min_length=1)
    realm: str = Field(min_length=1)
    dlc: str = Field(min_length=1)
    year: int = Field(ge=2016, le=2100)
    perk_1: str = Field(min_length=1)
    perk_2: str = Field(min_length=1)
    perk_3: str = Field(min_length=1)
    difficulty: Difficulty
    power: str = Field(default="None", min_length=1)
    description: str = Field(min_length=1)
    image: Optional[str] = None
    movement_speed: str = Field(min_length=1)
    terror_radius: str = Field(min_length=1)
    height: str = Field(default="N/A", min_length=1)
    voice_actor: str = Field(min_length=1)


class CharacterUpdate(BaseModel):
    """Body for PATCH. Every field is optional, only the ones sent are changed."""
    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)

    name: Optional[str] = Field(default=None, min_length=1)
    character_code: Optional[str] = Field(default=None, min_length=1)
    role: Optional[Role] = None
    gender: Optional[str] = Field(default=None, min_length=1)
    origin: Optional[str] = Field(default=None, min_length=1)
    realm: Optional[str] = Field(default=None, min_length=1)
    dlc: Optional[str] = Field(default=None, min_length=1)
    year: Optional[int] = Field(default=None, ge=2016, le=2100)
    perk_1: Optional[str] = Field(default=None, min_length=1)
    perk_2: Optional[str] = Field(default=None, min_length=1)
    perk_3: Optional[str] = Field(default=None, min_length=1)
    difficulty: Optional[Difficulty] = None
    power: Optional[str] = Field(default=None, min_length=1)
    description: Optional[str] = Field(default=None, min_length=1)
    image: Optional[str] = None
    movement_speed: Optional[str] = Field(default=None, min_length=1)
    terror_radius: Optional[str] = Field(default=None, min_length=1)
    height: Optional[str] = Field(default=None, min_length=1)
    voice_actor: Optional[str] = Field(default=None, min_length=1)

    @model_validator(mode="after")
    def at_least_one_field(self):
        if not self.model_fields_set:
            raise ValueError("Send at least one field to update.")
        # A field that is NOT NULL in the database cannot be set to null
        for field in self.model_fields_set:
            if field != "image" and getattr(self, field) is None:
                raise ValueError(f"'{field}' cannot be null.")
        return self


# ============================================================
# DATABASE LAYER
# All Supabase calls live here so the endpoints stay simple.
# ============================================================
SORTABLE = ("name", "year", "difficulty", "character_code")

# Text columns the keyword search looks at (year is handled separately)
SEARCH_COLUMNS = (
    "name", "character_code", "role", "gender", "origin", "realm", "dlc",
    "perk_1", "perk_2", "perk_3", "difficulty", "power", "description",
    "movement_speed", "terror_radius", "height", "voice_actor",
)

_client: Optional[Client] = None


class DatabaseUnavailable(Exception):
    """Raised when the database cannot be reached or is not configured."""


class DuplicateCharacter(Exception):
    """Raised when character_code is already used by another record."""


def get_client() -> Client:
    global _client
    if _client is None:
        if not SUPABASE_URL or not SUPABASE_SERVICE_KEY:
            logger.error("SUPABASE_URL or SUPABASE_SERVICE_KEY is not set.")
            raise DatabaseUnavailable()
        try:
            _client = create_client(SUPABASE_URL, SUPABASE_SERVICE_KEY)
        except Exception:
            logger.exception("Could not create the Supabase client.")
            raise DatabaseUnavailable()
    return _client


def run(query):
    """Execute a query and translate database errors into our own exceptions.
    The real error is only logged on the server, never sent to the client."""
    try:
        return query.execute()
    except APIError as e:
        if getattr(e, "code", None) == "23505":  # unique_violation
            raise DuplicateCharacter()
        logger.error("Database query failed: %s", e)
        raise DatabaseUnavailable()
    except DatabaseUnavailable:
        raise
    except Exception:
        logger.exception("Unexpected database error.")
        raise DatabaseUnavailable()


def db_count(role: Optional[str] = None) -> int:
    q = get_client().table(TABLE).select("id", count="exact")
    if role:
        q = q.eq("role", role)
    return run(q.limit(1)).count or 0


def db_list(role: Optional[str], sort_by: str, order: str, limit: int, offset: int):
    q = get_client().table(TABLE).select("*", count="exact")
    if role:
        q = q.eq("role", role)
    q = q.order(sort_by, desc=(order == "desc")).order("id")
    res = run(q.range(offset, offset + limit - 1))
    return res.data, res.count or 0


def db_search(term: str, limit: int, offset: int):
    # Strip characters that have special meaning in a PostgREST filter or ILIKE pattern
    clean = re.sub(r'[%*_\\"(),]', " ", term).strip()
    if not clean:
        return [], 0
    conditions = [f'{col}.ilike."*{clean}*"' for col in SEARCH_COLUMNS]
    if clean.isdigit():
        # year and id are numbers, so they need an exact match instead of ILIKE
        conditions.append(f"year.eq.{int(clean)}")
        conditions.append(f"id.eq.{int(clean)}")
    q = (
        get_client().table(TABLE)
        .select("*", count="exact")
        .or_(",".join(conditions))
        .order("name")
        .order("id")
    )
    res = run(q.range(offset, offset + limit - 1))
    return res.data, res.count or 0


def db_get(character_id: int):
    res = run(get_client().table(TABLE).select("*").eq("id", character_id).limit(1))
    return res.data[0] if res.data else None


def db_create(data: dict):
    res = run(get_client().table(TABLE).insert(data))
    return res.data[0]


def db_update(character_id: int, data: dict):
    res = run(get_client().table(TABLE).update(data).eq("id", character_id))
    return res.data[0] if res.data else None


def db_delete(character_id: int):
    res = run(get_client().table(TABLE).delete().eq("id", character_id))
    return res.data[0] if res.data else None


# ============================================================
# AUTHENTICATION
# ============================================================
def _matches(sent: Optional[str], expected: Optional[str]) -> bool:
    if not sent or not expected:
        return False
    return secrets.compare_digest(sent.encode(), expected.encode())


def verify_api_key(x_api_key: Optional[str] = Header(default=None)):
    """Read access. Used by the web apps."""
    if not _matches(x_api_key, API_KEY):
        raise HTTPException(status_code=401, detail="Invalid or missing API key.")
    return True


def verify_admin_key(x_admin_key: Optional[str] = Header(default=None)):
    """Write access (create, update, delete)."""
    if not _matches(x_admin_key, ADMIN_API_KEY):
        raise HTTPException(status_code=401, detail="Invalid or missing admin key.")
    return True


# ============================================================
# ERROR HANDLERS
# ============================================================
@app.exception_handler(DatabaseUnavailable)
async def database_unavailable_handler(request: Request, exc: DatabaseUnavailable):
    return JSONResponse(
        status_code=503,
        content={"detail": "The database is temporarily unavailable. Please try again later."},
    )


@app.exception_handler(DuplicateCharacter)
async def duplicate_handler(request: Request, exc: DuplicateCharacter):
    return JSONResponse(
        status_code=409,
        content={"detail": "A character with that character_code already exists."},
    )


@app.exception_handler(RequestValidationError)
async def validation_handler(request: Request, exc: RequestValidationError):
    # Return only the field and message, not the submitted values
    errors = [
        {"field": ".".join(str(p) for p in e["loc"] if p != "body"), "message": e["msg"]}
        for e in exc.errors()
    ]
    return JSONResponse(status_code=422, content={"detail": "Invalid request.", "errors": errors})


@app.exception_handler(Exception)
async def unexpected_error_handler(request: Request, exc: Exception):
    logger.exception("Unhandled error")
    return JSONResponse(status_code=500, content={"detail": "Something went wrong on the server."})


