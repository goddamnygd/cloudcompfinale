# ============================================================
# GET ALL CHARACTERS (read key)
# ============================================================
@app.get("/api/v1/characters", dependencies=[Depends(verify_api_key)])
def get_characters(
    role: Optional[str] = Query(None, description="Filter by 'Survivor' or 'Killer'"),
    sort_by: Literal["name", "year", "difficulty", "character_code"] = Query("name", description="Sort field"),
    order: Literal["asc", "desc"] = Query("asc", description="'asc' or 'desc'"),
    limit: int = Query(10, ge=1, le=100, description="Items per page"),
    offset: int = Query(0, ge=0, description="Page starting offset")
):
    role_filter = None
    if role:
        role_filter = role.strip().capitalize()
        if role_filter not in ("Survivor", "Killer"):
            raise HTTPException(status_code=422, detail="role must be 'Survivor' or 'Killer'.")

    rows, total = db_list(role_filter, sort_by, order, limit, offset)
    return {
        "total": total,
        "limit": limit,
        "offset": offset,
        "characters": rows
    }


# ============================================================
# SEARCH CHARACTERS (read key)
# This route must stay above /{character_id} so "search" is not read as an id.
# ============================================================
@app.get("/api/v1/characters/search", dependencies=[Depends(verify_api_key)])
def search_characters(
    q: str = Query(..., min_length=1, max_length=100),
    limit: int = Query(10, ge=1, le=100),
    offset: int = Query(0, ge=0)
):
    rows, total = db_search(q, limit, offset)
    return {
        "query": q,
        "total": total,
        "limit": limit,
        "offset": offset,
        "results": rows
    }


# ============================================================
# GET ONE CHARACTER (read key)
# ============================================================
@app.get("/api/v1/characters/{character_id}", dependencies=[Depends(verify_api_key)])
def get_character(character_id: int):
    character = db_get(character_id)
    if character is None:
        raise HTTPException(status_code=404, detail="Character not found.")
    return character


# ============================================================
# CREATE CHARACTER (admin key)
# ============================================================
@app.post("/api/v1/characters", status_code=201, dependencies=[Depends(verify_admin_key)])
def create_character(body: CharacterCreate):
    return db_create(body.model_dump())


# ============================================================
# UPDATE CHARACTER (admin key)
# Partial update: only the fields in the body are changed.
# ============================================================
@app.patch("/api/v1/characters/{character_id}", dependencies=[Depends(verify_admin_key)])
def update_character(character_id: int, body: CharacterUpdate):
    updated = db_update(character_id, body.model_dump(exclude_unset=True))
    if updated is None:
        raise HTTPException(status_code=404, detail="Character not found.")
    return updated


# ============================================================
# DELETE CHARACTER (admin key)
# ============================================================
@app.delete("/api/v1/characters/{character_id}", dependencies=[Depends(verify_admin_key)])
def delete_character(character_id: int):
    deleted = db_delete(character_id)
    if deleted is None:
        raise HTTPException(status_code=404, detail="Character not found.")
    return {"message": "Character deleted.", "id": character_id, "name": deleted["name"]}
